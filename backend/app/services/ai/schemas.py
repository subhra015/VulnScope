"""
Pydantic schemas for AI-assisted remediation, proposed fixes, and proposal lifecycle.
"""

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class AIRemediationRequest(BaseModel):
    """User request for AI remediation assistance with remote processing opt-in."""
    allow_remote: bool = Field(
        default=False,
        description="Explicit user consent to transmit sanitized finding context to configured remote AI provider.",
    )


class AIPatchRequest(BaseModel):
    """User request to generate a candidate source code fix patch."""
    allow_remote: bool = Field(
        default=False,
        description="Explicit user consent to transmit sanitized finding context to configured remote AI provider.",
    )


class AIRemediationResponseSchema(BaseModel):
    """Structured Pydantic response format expected from AI providers."""
    explanation: str = Field(..., description="Concise explanation of the security finding")
    likely_root_cause: str = Field(..., description="Root cause explanation qualified with available evidence")
    potential_impact: str = Field(..., description="Realistic impact grounded strictly in finding context")
    remediation_steps: List[str] = Field(..., description="Step-by-step remediation plan")
    secure_coding_pattern: Optional[str] = Field(default=None, description="Recommended safe code pattern")
    testing_recommendations: List[str] = Field(..., description="Unit or security testing recommendations")
    caveats_and_assumptions: List[str] = Field(..., description="Caveats, assumptions, and missing context")
    patch_appropriate: bool = Field(
        default=False,
        description="Whether a repository source code diff is safe and appropriate for this finding",
    )


class AIPatchResponseSchema(BaseModel):
    """Structured patch response format expected from AI providers."""
    target_file_path: str = Field(..., description="Repository-relative target file path")
    change_summary: str = Field(..., description="Brief summary of proposed source code changes")
    diff_content: str = Field(..., description="Valid unified diff starting with '--- a/' and '+++ b/'")


class RemediationProposalResponse(BaseModel):
    """API response model for a RemediationProposal entity."""
    id: str
    scan_id: str
    finding_id: str
    finding_fingerprint: Optional[str] = None
    status: str = Field(
        ...,
        description="Proposal lifecycle: 'proposed', 'reviewed', 'rejected', 'downloaded', 'validation_failed', 'verification_pending', 'verified_by_rescan', 'unconfirmed'",
    )
    provider: str
    model_name: str
    explanation: str
    likely_root_cause: str
    potential_impact: str
    remediation_steps: List[str]
    secure_coding_pattern: Optional[str] = None
    testing_recommendations: List[str]
    caveats_and_assumptions: List[str]
    patch_appropriate: bool
    target_file_path: Optional[str] = None
    change_summary: Optional[str] = None
    diff_content: Optional[str] = None
    validation_error: Optional[str] = None
    user_notes: Optional[str] = None
    is_ai_generated: bool = True
    disclaimer: str = (
        "Proposal generated by AI. This suggestion is not an authoritative security guarantee. "
        "Review carefully and rescan to verify remediation."
    )
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class UpdateProposalStatusRequest(BaseModel):
    """Request payload to advance or update proposal lifecycle state."""
    status: str = Field(
        ...,
        description="New proposal state ('reviewed', 'rejected', 'verification_pending')",
    )
    user_notes: Optional[str] = Field(default=None, max_length=2000, description="Optional user review notes")
